import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { renderBlogArticleHtml } from "./blog-markdown-renderer.mjs";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const blogRoot = path.join(repoRoot, "blogs");
const imageManifestPath = path.join(repoRoot, "public", "assets", "openstudio", "generated", "image-manifest.json");
const outputRoot = path.join(repoRoot, "src", "data", "generatedBlogContent");

const entries = await fs.readdir(blogRoot, { withFileTypes: true });
const filenames = entries
  .filter((entry) => entry.isFile() && entry.name.toLowerCase().endsWith(".md") && entry.name.toLowerCase() !== "readme.md")
  .map((entry) => entry.name)
  .sort();
const imageManifest = JSON.parse(await fs.readFile(imageManifestPath, "utf8"));

await fs.mkdir(outputRoot, { recursive: true });

const keepFiles = new Set();
for (const filename of filenames) {
  const markdown = await fs.readFile(path.join(blogRoot, filename), "utf8");
  const articleHtml = renderBlogArticleHtml(markdown, imageManifest);
  const outputName = filename.replace(/\.md$/i, ".ts");
  const outputPath = path.join(outputRoot, outputName);
  const output = [
    "// Generated by scripts/generate-blog-content.mjs from trusted local Markdown.",
    `const articleHtml = ${JSON.stringify(articleHtml)};`,
    "",
    "export default articleHtml;",
    "",
  ].join("\n");

  keepFiles.add(outputPath);
  await fs.writeFile(outputPath, output, "utf8");
}

for (const entry of await fs.readdir(outputRoot, { withFileTypes: true })) {
  const outputPath = path.join(outputRoot, entry.name);
  if (entry.isFile() && entry.name.endsWith(".ts") && !keepFiles.has(outputPath)) {
    await fs.unlink(outputPath);
  }
}

console.log(`[blogs] generated controlled article HTML for ${filenames.length} post${filenames.length === 1 ? "" : "s"}.`);
