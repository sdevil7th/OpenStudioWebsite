import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { chromium } from "playwright";
import sharp from "sharp";
import ts from "typescript";

const source = await readFile(new URL("../src/features/hero-aura/renderer.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS },
}).outputText;
const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  const png = await page.evaluate((source) => {
    const exports = {};
    new Function("exports", source)(exports);
    const canvas = document.createElement("canvas");
    const paint = exports.createAuraPainter(canvas);
    if (!paint) throw new Error("Cannot render the hero's static frame");
    paint(0);
    return canvas.toDataURL("image/png").split(",")[1];
  }, compiled);
  const webp = await sharp(Buffer.from(png, "base64")).webp({ lossless: true }).toBuffer();
  const directory = new URL("../public/assets/openstudio/backgrounds/", import.meta.url);
  await mkdir(directory, { recursive: true });
  await writeFile(new URL("hero-aura-rest.webp", directory), webp);
  const hash = createHash("sha256").update(webp).digest("hex").slice(0, 14);
  await writeFile(new URL("../src/features/hero-aura/generatedRestFrame.ts", import.meta.url),
    `// Generated by npm run generate-hero-aura from renderer.ts; do not edit.\n` +
    `export const AURA_REST_FRAME = "/assets/openstudio/backgrounds/hero-aura-rest.webp?v=${hash}";\n`);
  console.log(`[hero-aura] generated the renderer's exact first frame (${webp.length} bytes)`);
} finally {
  await browser.close();
}
