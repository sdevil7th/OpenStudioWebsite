/** Build-time data comes from GitHub. No manually maintained release numbers or asset sizes. */
import fs from "node:fs/promises";
import path from "node:path";
import { createServer } from "vite";

const root = path.resolve(import.meta.dirname, "..");
const output = path.join(root, "public/github");
await fs.mkdir(output, { recursive: true });
const server = await createServer({
  configFile: false,
  root,
  appType: "custom",
  optimizeDeps: { noDiscovery: true, include: [] },
  logLevel: "error",
  server: { middlewareMode: true },
});
try {
  const { fetchGithubRepoSnapshot } = await server.ssrLoadModule("/shared/github-api.ts");
  let snapshot;
  try {
    snapshot = await fetchGithubRepoSnapshot(process.env.GITHUB_TOKEN);
  } catch (error) {
    // Local iteration can survive a temporary API outage/quota limit without inventing release values.
    // Clean CI/Netlify builds still require a successful GitHub fetch.
    if (process.env.CI || process.env.NETLIFY) throw error;
    const cached = JSON.parse(await fs.readFile(path.join(output, "repository.json"), "utf8").catch(() => "null"));
    const age = Date.now() - Date.parse(cached?.fetchedAt ?? "");
    if (
      !cached?.latestRelease ||
      cached.fullName !== (process.env.OPENSTUDIO_DESKTOP_REPO || "sdevil7th/OpenStudio") ||
      !Number.isFinite(age) ||
      age < 0 ||
      age > 24 * 60 * 60 * 1000
    )
      throw error;
    snapshot = cached;
    console.warn(
      `GitHub unavailable; reusing the verified local snapshot from ${snapshot.fetchedAt}. ${error.message}`,
    );
  }
  if (!snapshot.latestRelease) throw new Error("GitHub has no published stable desktop release.");
  const { selectReleaseAsset } = await server.ssrLoadModule("/shared/release-assets.ts");
  const latest = snapshot.latestRelease;
  const assets = ["windows", "macos", "linux"]
    .map((platform) => selectReleaseAsset(latest.assets, platform))
    .filter(Boolean);
  const { body: _body, ...summary } = latest;
  const lightweightRelease = { ...summary, assets };
  await fs.writeFile(path.join(output, "repository.json"), JSON.stringify(snapshot));
  await fs.writeFile(path.join(output, "latest-release.json"), JSON.stringify(lightweightRelease));
  const preamble = `// Generated by scripts/sync-github-data.mjs from GitHub at ${snapshot.fetchedAt}. Do not edit.\n`;
  await fs.writeFile(
    path.join(root, "src/data/generatedGithubSnapshot.ts"),
    `${preamble}import type { GithubRepoSnapshot } from "./marketing";\nexport const generatedGithubSnapshot: GithubRepoSnapshot = ${JSON.stringify(snapshot)};\n`,
  );
  await fs.writeFile(
    path.join(root, "src/data/generatedLatestRelease.ts"),
    `${preamble}import type { GithubReleaseSummary } from "./marketing";\nexport const generatedLatestRelease: GithubReleaseSummary = ${JSON.stringify(lightweightRelease)};\n`,
  );
  console.log(`GitHub: ${latest.tagName}, ${assets.length} desktop installers, fetched ${snapshot.fetchedAt}`);
} finally {
  await server.close();
}
